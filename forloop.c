// WAP TO PRINT HELLO WORLD 100 TIMES //

#include <stdio.h>

int main()
{
    // INITIALIZATION WORKS FOR THE FIRST TIME TO START THE LOOP
    // CONDITION IS CHECKED, THEN PRINTING HAPPENS,
    // THEN VALUE UPDATES AND CONDITION IS CHECKED AGAIN

    for (int i = 1; i <= 100; i = i + 1)
    {
        printf("HELLO WORLD \n");
    }

    return 0;
}